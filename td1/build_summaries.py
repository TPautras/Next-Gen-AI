#!/usr/bin/env python3
"""TD 1 step 2-3: merge the operators' raw CSVs into traces-td1.csv (one header,
every attempt kept, chronological), then derive from it:

- model-question-comparison-en.csv: one final row per model/question (last
  attempt), explanation taken from td1/explanations.json (hand-written after
  reading the SQL and error fields of each failing cell);
- td1/pivot-models-x-questions.md: the models x questions view of that CSV;
- td1/family-results.json: correct/evaluated per question family, used in
  five-model-summary-en.csv.

    python3 td1/build_summaries.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MEMBERS = "ABCDE"
SHORT = {"openai/gpt-oss-120b": "gpt-oss-120b", "openai/gpt-oss-20b": "gpt-oss-20b",
         "cohere/north-mini-code:free": "north-mini-code", "qwen/qwen3.8-27b": "qwen3.8-27b",
         "dots-studio/dots-3-note-preview:free": "dots-3-note"}
FAMILIES = {"period": "period", "age": "age", "product": "product list"}


def read_csv(path):
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def main() -> int:
    rows, source = [], {}
    for member in MEMBERS:
        path = ROOT / "traces" / f"traces-{member}.csv"
        for index, row in enumerate(read_csv(path), start=2):        # line 1 is the header
            rows.append(row)
            source[id(row)] = f"traces/traces-{member}.csv:{index}"
    rows.sort(key=lambda r: (r["date_utc"], r["cell_id"], int(r["attempts"])))
    header = list(rows[0])
    with (ROOT / "traces-td1.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=header, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    with (ROOT / "traces-td1.jsonl").open("w", encoding="utf-8") as stream:
        for row in rows:
            stream.write(json.dumps(row, ensure_ascii=False) + "\n")

    explanations = json.loads((ROOT / "td1" / "explanations.json").read_text(encoding="utf-8"))
    latest = {}
    for row in rows:
        latest[row["cell_id"]] = row
    questions = {q["id"]: q for q in json.loads((ROOT / "questions-td1.json").read_text())["questions"]}
    models = list(SHORT)
    comparison = []
    for model in models:
        for case_id in sorted(questions):
            cell = next((r for r in latest.values() if r["model_requested"] == model and r["case_id"] == case_id), None)
            if cell is None:
                comparison.append({"case_id": case_id, "model_id": model, "trace_file": "", "cell_id": "",
                                   "nature": "", "status": "not_executed", "value_cents": "",
                                   "reference_cents": "", "explanation": "no attempt recorded"})
                continue
            attempts = sum(r["cell_id"] == cell["cell_id"] for r in rows)
            default = (f"value equals the reference; last attempt {cell['attempts']}"
                       if cell["verdict"] == "correct" else f"{cell['verdict']}: {cell['verdict_detail']}")
            text = explanations.get(cell["cell_id"], default)
            if attempts > 1:
                text += f" ({attempts} attempts in traces-td1.csv)"
            comparison.append({"case_id": case_id, "model_id": f"{cell['provider']}:{model}",
                               "trace_file": f"traces-td1.csv; {source[id(cell)]}", "cell_id": cell["cell_id"],
                               "nature": cell["nature"], "status": cell["verdict"], "value_cents": cell["value"],
                               "reference_cents": cell["reference"], "explanation": text})
    with (ROOT / "model-question-comparison-en.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(comparison[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(comparison)

    # Pivot view: models as rows, questions as columns, status as the value.
    mark = {"correct": "ok", "incorrect": "WRONG", "sql_invalid": "invalid", "sql_rejected": "rejected",
            "access_error": "access", "not_executed": "not run"}
    cases = sorted(questions)
    lines = ["# Models x questions (pivot of model-question-comparison-en.csv)", "",
             "Generated by `td1/build_summaries.py`; status of the last attempt per cell, nature = real.", "",
             "| model | " + " | ".join(cases) + " | correct |", "|---" * (len(cases) + 2) + "|"]
    for model in models:
        cells = {r["case_id"]: r for r in comparison if r["model_id"].endswith(":" + model)}
        good = sum(c["status"] == "correct" for c in cells.values())
        lines.append(f"| {SHORT[model]} | " + " | ".join(mark.get(cells[c]["status"], cells[c]["status"]) for c in cases)
                     + f" | {good}/20 |")
    lines += ["", "Question types: " + "; ".join(f"{c} {questions[c]['type']}" for c in cases)]
    (ROOT / "td1" / "pivot-models-x-questions.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    families = {}
    for model in models:
        cells = [r for r in comparison if r["model_id"].endswith(":" + model)]
        out = {}
        for key, label in FAMILIES.items():
            subset = [c for c in cells if label in questions[c["case_id"]]["type"]]
            out[key] = _count(subset)
        out["combined"] = _count([c for c in cells if "+" in questions[c["case_id"]]["type"]])
        out["all"] = _count(cells)
        out["wrong_cases"] = [c["case_id"] for c in cells if c["status"] != "correct"]
        families[model] = out
    (ROOT / "td1" / "family-results.json").write_text(json.dumps(families, indent=1) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(json.dumps(families, indent=1))
    return 0


def _count(cells):
    evaluated = [c for c in cells if c["status"] in ("correct", "incorrect", "sql_invalid", "sql_rejected")]
    return {"correct": sum(c["status"] == "correct" for c in cells), "evaluated": len(evaluated),
            "access_or_unfinished": len(cells) - len(evaluated), "cases": [c["case_id"] for c in cells]}


if __name__ == "__main__":
    raise SystemExit(main())
